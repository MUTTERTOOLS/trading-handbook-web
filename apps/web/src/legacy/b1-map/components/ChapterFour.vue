    <h3 id="c04-s5" class="sub-title" data-spy>五、这张表怎么用、不能怎么用</h3>
    <p>五个用法：</p>
    <ol>
      <li><strong>听完任何"方法"或"消息"，花两分钟拆格。</strong>不用反驳内容，先看缺哪些格——缺格越多的说法，越接近纯情绪。</li>
      <li><strong>写计划时按格自查。</strong>六格里哪格空着，就先补哪格，补不上就不动手；写不出的格，往往就是将来亏损的来源。</li>
      <li><strong>复盘时按格归档。</strong>把当天的信息与执行放进对应的格，才分得清是信息错了还是执行错了。</li>
      <li><strong>用在别人身上要克制。</strong>拆格是为了识别信息缺口，不是为了在争论里占上风；要紧的是自己别跟着一份填不满的计划走。</li>
      <li><strong>定期回看。</strong>看看自己的空格是不是总缺同样几格。多数人的缺格是固定的，看见它，就找到了最该补的课。</li>
    </ol>
    <p>两条限制：</p>
    <ol>
      <li>表不产出买卖结论。格子填满，只说明信息齐了；方法是否有效，要另行验证（后文〔B1-C06〕还有一份更严格的检查清单）。</li>
      <li>分类不保证穷尽。真实交易里还有跨格的信息、难以归类的信息，遇到时放最接近的格，并在备注里写明。</li>
    </ol>

    <h3 id="c04-m" class="sub-title" data-spy>常见误区</h3>
    <Callout variant="warn" title="误区一：“六个字是完全独立的六个维度。”">
      <p>
        <strong>为什么错：</strong>六格高度相关：价量本来就一起看，风会影响价，时是其他格的坐标，心依附于计划。
        把六格当独立原子，会让人以为"每格各采一个数据"就算信息完整，反而漏掉交叉验证。
      </p>
      <p><strong>正确做法：</strong>把六格当检查表：填格时允许一个信息写进两格，注明主格；读表时做交叉解读。</p>
    </Callout>
    <Callout variant="warn" title="误区二：“有了这套分类，就知道该买什么了。”">
      <p>
        <strong>为什么错：</strong>分类是整理信息的工具，不产出买卖结论；它回答"我知道了什么、缺什么"，不回答"买不买、买多少"。
        把检查表当决策引擎，等于拿着体温计找路。
      </p>
      <p><strong>正确做法：</strong>拆格之后，接着回答收益来源三问〔B1-C02〕、算期望〔B1-C03〕，再按流程把信息写成规则与计划。</p>
    </Callout>
    <Callout variant="warn" title="误区三：“风就是消息，有消息就是买点。”">
      <p>
        <strong>为什么错：</strong>风只是外部信息的背景格。消息传到普通投资者手里时通常已经不新鲜，真伪也没有核实；
        "有消息"与"该买入"之间隔着来源核实、定价与风险额度。
      </p>
      <p><strong>正确做法：</strong>风只入格，不直接触发买卖；消息先问来源与时效，再谈怎么用。</p>
    </Callout>

