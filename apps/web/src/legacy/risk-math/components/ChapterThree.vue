    <h3 id="c03-s4" class="sub-title" data-spy>四、把五步装进一天</h3>
    <p>
      <strong>盘前：做完①②③，写下④的条件。</strong>一页纸包含六样东西：环境判断一句、买入逻辑一句、止损价、股数与 1R、
      触发条件，以及一句"不触发则不做"。这张纸就是盘前快照，完整模板后文〔B7-C03〕详述。写完快照，当天的决策工作已经结束。
    </p>
    <p>
      <strong>盘中：只做第④步。</strong>触发条件出现，按快照执行；不出现，什么都不做。
      盘中冒出来的新想法——加仓、挪止损、改目标——只记录，不执行。
    </p>
    <p>
      <strong>盘后：做第⑤步。</strong>对账三问：今天有触发吗？执行与快照一致吗？偏差属于哪一类？
      答案写进记录（〔B7-C07〕）；要不要改规则，留到次日盘前决定，不在盘中改。
    </p>
    <p>
      这样安排之后，亏损有了清楚的归属：按五步走完再执行的亏损属于计划内亏损，是策略的成本（〔B3-C01〕）；
      从任何一步抄近路产生的亏损，事后看几乎都是计划外亏损。风控的目标不是消灭亏损，而是让亏损尽量发生在计划内。
    </p>
    <p>
      如果你只做宽基指数定投呢？五步仍然适用，只是极简：第①步变成"这笔钱几年内不动"（资金期限，〔B3-C11〕），
      第②步的定投规则事先选定并经过验证（〔B8-C03〕后文详述），第③④步合并为机械执行。骨架相同：先决定，后动手。
    </p>
    <p class="table-note">
      最后交代分工：第③步的算法在〔B3-C04〕，止损怎么定在〔B3-C05〕，止损失灵（跳空、停牌）在〔B3-C06〕，
      账户整体何时必须停手在〔B3-C10〕。本章只负责一件事：在下任何一笔交易之前，先把这五步的顺序摆对。
    </p>

    <h3 id="c03-m" class="sub-title" data-spy>常见误区</h3>
    <Callout variant="warn" title="误区一：“看环境、选结构太虚了，直接从找买点开始效率高。”">
      <p>
        <strong>为什么错：</strong>前两步决定"该不该做、做哪个"。跳过它们，第③步的数字再精确，也是在给一笔不该做的交易精确算账。
      </p>
      <p>
        <strong>正确做法：</strong>把两步写成可判定的句子（例如"基准指数收于 60 日线下方则当日不开新仓"）。
        觉得"虚"，通常是因为没有写成句子；写成句子后，这两步各只要一分钟。
      </p>
    </Callout>
    <Callout variant="warn" title="误区二：“五步太繁琐，熟练之后可以合并或省略几步。”">
      <p>
        <strong>为什么错：</strong>顺序的价值恰恰在状态最差、行情最急的时候，它替你扛住"现在就必须做个决定"的压力。
        省略几乎总发生在情绪最重的时刻：追涨时省掉①②，浮亏时省掉④⑤。熟练提高的是速度，不是次序。
      </p>
      <p><strong>正确做法：</strong>用盘前快照把五步固化成一页纸（后文〔B7-C03〕详述）。填一页纸以分钟计，换来盘中不需要再做任何新决定。</p>
    </Callout>
    <Callout variant="warn" title="误区三：“亏损说明计划错了，盘中修正（挪止损、加仓、改长线）才是负责任。”">
      <p>
        <strong>为什么错：</strong>计划内亏损是成本，不是计划出错的信号（〔B3-C01〕）。
        把它当成错误信号去"修正"，改动却发生在信息最差、情绪最重的盘中——三种错误顺序全是这样开始的。
      </p>
      <p>
        <strong>正确做法：</strong>触发即执行；对计划的不满写进盘后记录，改动放到下一次盘前快照。
        涉及方法本身的改动须走重新验证流程（后文〔B7-C09〕详述）。
      </p>
    </Callout>

