    <h3 id="c03-s3" class="sub-title" data-spy>三、错误顺序的三种典型</h3>
    <p>
      完整跳过五步的人不多，常见的是从中间"抄近路"。三条最常见的近路，每一条都能用乘法算出代价。本章唯一用到的式子：
    </p>
    <div class="formula-block">计划亏损 = 持仓股数 ×（入场价 − 止损价）</div>
    <p>
      这是〔B3-C04〕仓位公式的简化用法：给定股数与止损，计划亏损就确定了。
      口径沿用 EX-A 与 EX-B：本金 100,000 元，甲股份入场 10.00 元；为便于只看顺序，用不含滑点的简化口径；
      单笔风险预算取 1%，即 1R = 1,000 元（起步参考值，需个人校准）。
    </p>
    <p>
      <strong>典型一：先买后找止损。</strong>小明没做①②，凭"感觉要涨"下单 20,000 元买入 2,000 股，占本金 20%，正好顶到单票上限。
      买完才找止损：像样的逻辑其实是"箱体突破"，失效点在 8.50 元（独立示意）。此时两个选择都不好：
    </p>
    <ul>
      <li>坚持失效点 8.50 元：每股风险 1.50 元，计划亏损 = 2,000 × 1.50 = 3,000 元，占本金 3%，是预算的 3 倍。</li>
      <li>
        把止损挪近到 9.50 元：计划亏损 = 1,000 元，回到预算内；但 9.50 不是失效点，
        位置是被"我想让亏损小一点"倒逼出来的，落在正常波动范围内，容易被噪音打掉（〔B3-C05〕）。
      </li>
    </ul>
    <p>
      如果按正确顺序：先定 1R = 1,000 元，再取失效点 8.50 元，那么股数 = 1,000 ÷ 1.50 ≈ 666.7，向下取整为 600 股，
      金额 6,000 元（6%），计划亏损 = 900 元。同一次判断，同一个失效点，仅仅顺序不同，计划亏损相差 3,000 ÷ 900 ≈ 3.3 倍。
      <strong>先买后找止损的实质，是让仓位反过来决定止损。</strong>
    </p>
    <p>
      <strong>典型二：套牢后改口长线。</strong>小明这次按五步走：突破结构，失效点 9.50 元（前期低点），2,000 股，1R = 1,000 元。
      几天后价格跌破 9.50，触发成立，他想"再观察一天"，没有执行。三天后价格到 9.20 元，浮亏 = 1,600 元，已是 1.6R。
      他改口："甲股份行业前景好，我本来就该做长线。"
    </p>
    <p>
      问题不在"长线"本身，而在于这是一套从未走过的流程：长线持有也是一套结构，需要自己的环境判断、买入逻辑、证伪条件、仓位与退出规则
      （买入理由与退出条件的对应关系见〔B3-C09〕）。改口之后，结构换了，退出没了，亏损上限从 1,000 元变成"未知"。
      如果长线确实值得做，先按原规则离场，盘后为它单独走一遍五步——<strong>过不过得了第①②步，让流程判断，不让浮亏判断。</strong>
    </p>
    <p>
      <strong>典型三：亏了加仓摊低。</strong>还是那笔合格的 2,000 股、止损 9.50。跌破 9.50 时他没卖；跌到 9.00 元，他加仓 2,000 股，
      理由是"把成本摊下来"。摊下来的成本是（10.00 + 9.00）÷ 2 = 9.50 元，数字看着舒服了，风险却变了样：
    </p>
    <ul>
      <li>总投入 38,000 元，占本金 38%，远超单票上限 20%（起步参考值）。</li>
      <li>若继续跌到 8.50 元，亏损 = 4,000 × 1.00 = 4,000 元，等于 4R，占本金 4%。</li>
      <li>最关键的是找不到止损：原失效点 9.50 已被跌穿两次，加仓不对应任何新逻辑。</li>
    </ul>
    <p>
      加仓那一刻，①②③④全部被跳过。这个动作在〔B3-C02〕里被列为四种破产结构之一（亏损加仓）；
      "跌下来买更便宜"为什么感觉有道理，行为解释见〔B7-C02〕。
    </p>
