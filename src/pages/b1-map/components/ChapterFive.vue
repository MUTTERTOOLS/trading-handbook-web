    <h3 id="c05-s3" class="sub-title" data-spy>三、分层是工程划分，不是三种东西</h3>
    <p>把系统分层，是为了分工检查，不是为了把它们切成互不相干的三块。两个小数字例就能说明层与层缠得有多紧。</p>
    <p>
      <strong>例子一：止损宽度同时改变胜率与赔率。</strong>（本例数字为独立示意）甲股份现价 10.00 元，小明定的目标价是 11.00 元。
      按盈亏比公式（〔B1-C03〕）：盈亏比 = (目标价 − 入场价) ÷ (入场价 − 止损价)。
    </p>
    <ul>
      <li>止损 9.80 元：盈亏比 = 1.00 ÷ 0.20 = 5</li>
      <li>止损 9.50 元：盈亏比 = 1.00 ÷ 0.50 = 2</li>
    </ul>
    <p>
      止损收到 9.80，每笔亏得少，盈亏比漂亮；但若这只股票日常就有 3% 左右的波动，跌 2% 的止损位很容易在逻辑没变时被日常波动扫掉，胜率被拉低。
      放宽到 9.50，被扫的次数减少，胜率可能上升，可盈亏比从 5 掉到 2。
      同一个参数，写在规则层，却一手按着胜率，一手按着赔率——这两个数正是认知层算期望时的输入（〔B1-C03〕）。不存在"各层各管各、互不影响"的好事。
    </p>
    <p>
      <strong>例子二：仓位同时影响增长率与破产概率。</strong>仓位大，赚的时候账户涨得快，这是它影响"增长率"的一面；
      但连亏是常态（〔B6-C02〕），仓位大也放大连亏的破坏。按 EX-I（起步参考值，需个人校准）：
      单笔风险 1%，连亏 7 笔后回撤约 6.8%；单笔风险 5%，连亏 6 笔回撤就到约 26.5%，已经越过 15% 的账户硬上限（起步参考值，详见〔B3-C10〕）。
      这就是它影响"破产概率"的一面。
    </p>
    <p>
      所以不要用"多买一点"去补工具的不足，那是拿破产概率换增长率。结论：分层是工程划分。
      检查系统时分层查，运行时它们是联动的整体；任何一层改动，都要回到验证流程重新过一遍（后文〔B6〕详述）。
    </p>

