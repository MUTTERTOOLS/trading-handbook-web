    <h3 id="c01-m" class="sub-title" data-spy>常见误区</h3>
    <Callout variant="warn" title="误区一：“长期持有就是投资，短线就是赌博。”">
      <p>
        <strong>为什么错：</strong>区分三类的尺子是三问，不是时长。长期持有若没有退出考虑、没有风险预案，只是"拖得久的赌博式操作"；
        短线若规则明确、每笔亏损有额度、可复盘，就是交易。把时长当标准，会让人对长线放松警惕。
      </p>
      <p><strong>正确做法：</strong>对任何操作，包括"拿着不动"的持仓，都过一遍三问。</p>
    </Callout>
    <Callout variant="warn" title="误区二：“赚钱就是做对了，亏钱就是做错了。”">
      <p>
        <strong>为什么错：</strong>单笔结果里混着大量运气：违规重仓可能正好碰上涨，按规则执行的亏损可能只是正常波动。
        用单笔结果评价做法，会把人越训越歪。亏损的原因要分三类——方差、执行偏差、策略失效，后文〔B7-C01〕详述。
      </p>
      <p><strong>正确做法：</strong>用过程评价单笔（是否按事先写下的规则执行），用一串结果评价方法（要多少笔、怎么算，见〔B1-C03〕）。</p>
    </Callout>
    <Callout variant="warn" title="误区三：“我不卖就不算亏，扛到回本就行。”">
      <p>
        <strong>为什么错：</strong>账户亏了多少，看的是市值，不是有没有卖出。不卖不改变亏损的事实，还占着资金、堵着其他选择；
        "扛到回本"也没有回答"如果继续跌怎么办"。
      </p>
      <p><strong>正确做法：</strong>用账户总权益看待自己的本金（口径见〔B3-C04〕）；持仓也按三问归类，给它补上书面的退出条件（退出的完整规则后文〔B3-C09〕详述）。</p>
    </Callout>

