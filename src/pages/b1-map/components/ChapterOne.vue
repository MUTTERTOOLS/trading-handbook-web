    <h3 id="c01-s3" class="sub-title" data-spy>三、每一笔成交，都有对手盘</h3>
    <p>你想买，一定有人在卖；你想卖，一定有人在买。成交的另一边，就是<strong>对手盘</strong>。</p>
    <p>下单前值得问一句：对面是谁，他为什么愿意在这个价格和我成交？这个问题不是要你猜出对方的身份，而是强迫你想清楚交易的另一侧逻辑。可能的答案有很多种。</p>
    <ul>
      <li>对方可能需要现金，今天就要用钱，价格差一点也认了。</li>
      <li>对方可能受规则约束，必须按时间表买卖，挑不了时机。</li>
      <li>对方可能认真研究过，判断与你正好相反。</li>
      <li>对方也可能和你一样，只是听了一个消息。</li>
    </ul>
    <p>
      这些答案各有各的含义，下一章会按"收益来源"逐类展开。这个问题还有一个隐藏用途：
      如果想了半天，理由只剩下"对方会犯傻"，那么多半是你自己还没想清楚。它还能拦住另一种冲动：想"教育"市场——
      想清楚对面是谁之后，多数"市场错了，我来纠正它"的念头会自己熄火，纠正市场需要的资金量也不在个人账户的量级里。
    </p>
    <p>对手盘也不一定是敌人。很多时候，双方只是需求不同：他要现金，你要资产；他必须今天卖，你可以等。市场里大量的成交，本来就是各取所需。</p>
    <p>
      这个问题还有个练习办法：每做一笔，写下"我以为对面是谁"。攒上十几笔再看，你反复给出的理由往往只有一两种——
      那就是你目前唯一的利润假设，值得单独检验。
    </p>

    <h3 id="c01-s4" class="sub-title" data-spy>四、零和、正和、负和：先立三个词</h3>
    <p><strong>正和</strong>：所有参与者的合计收益可以大于零，因为盘子本身在变大——普通投资者凭什么分到这份收益，下一章展开。</p>
    <p><strong>零和</strong>：你的盈利来自别人的亏损，双方合计为零——交易者之间的价差博弈在不计成本时就是零和，这些价差的钱从哪来，下一章展开。</p>
    <p>
      <strong>负和</strong>：交易者之间的价差博弈，每一次买卖都要付佣金、印花税，还要面对买卖价差（〔B2-C05〕有费用全清单），
      所以扣除费用后合计为负，平均下来交易者是净支出方——负和游戏里谁还在赚，下一章展开。
    </p>
    <p>
      <strong>类比（零和与负和）：</strong>四个人打扑克，筹码只在玩家之间流动，这是零和；如果牌桌每局还要抽水，就成了负和。
      *类比的局限：*扑克的输赢只取决于玩家，而股票连着企业盈利，所以牌桌比喻只适合"交易者之间的价差博弈"这一部分，不能套在市场整体上。
    </p>
