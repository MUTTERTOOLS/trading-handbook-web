    <h3 id="c03-s2" class="sub-title" data-spy>二、期望收益：把很多笔压成一个数</h3>
    <p>
      单笔结果主要由运气决定，可比的是"平均每一笔"。<strong>期望收益</strong>（记作 E）指同样的操作重复很多次后，平均每笔的预期得失。
      四个输入只回答一个问题：把输赢和成本都摊到每一笔头上，天平倒向哪边。它的公式是：
    </p>
    <div class="formula-block">E = 胜率 × 平均盈利 − 败率 × 平均亏损 − 摩擦成本</div>
    <p>四个输入逐个说明：</p>
    <ul>
      <li><strong>胜率</strong>：盈利笔数除以总笔数。败率 = 1 − 胜率。</li>
      <li><strong>平均盈利</strong>：所有盈利笔的平均幅度。本书用每笔的百分比口径（与常量表一致），用金额结果相同。</li>
      <li><strong>平均亏损</strong>：所有亏损笔的平均幅度，代入公式时取正数。注意用真实发生的亏损，不是计划亏损——两者的差距本身说明问题（〔B3-C08〕会专门讲）。</li>
      <li><strong>摩擦成本</strong>：每笔买卖要付的佣金、印花税，以及买卖价差的损耗。全清单见〔B2-C05〕，本章常按一笔 0.2% 的口径举例（独立示意）。</li>
    </ul>
    <p>
      这四个数不是拍脑袋估的：要么来自自己的逐笔记账（〔B7-C07〕），要么来自把规则放到历史数据上统计（〔B6-C12〕）。
      两样都没有，E 就只能是编的。
    </p>
    <p>
      <strong>类比：</strong>一台天平。左盘放赢得的部分：胜率乘平均盈利；右盘放输掉的部分：败率乘平均亏损，再压上一个砝码——摩擦成本。
      左盘沉，长期平均赚；右盘沉，长期平均亏。*类比的局限：*天平两边的重量是确定的，而期望收益的四个输入都是估计值，会随市场与执行情况变化。
    </p>
    <p>动手算之前先固定口径：用百分比还是用 R，数据来自哪本账。口径混着用，是天平失真的第一步。</p>
    <p>用常量表里的第一个算例走一遍（EX-E：高胜率也可能亏钱）。已知：胜率 80%，平均盈利 2%，平均亏损 10%，成本暂不计。</p>
    <ul>
      <li>第一步，求败率：1 − 80% = 20%。</li>
      <li>第二步，算左盘：80% × 2% = 1.6%。</li>
      <li>第三步，算右盘：20% × 10% = 2.0%。</li>
      <li>第四步，相减：E = 1.6% − 2.0% = <strong>−0.4%/笔</strong>。</li>
    </ul>
    <p>
      <strong>复算（换一种算法核对）：</strong>这组数据的盈亏比是 2% ÷ 10% = 0.2。按下一节的平衡表，盈亏比 0.2 要求胜率约 83.3% 才打平，
      实际只有 80%，低于平衡线，应当亏——两种算法结论一致，E 为负可信。
    </p>
    <p>
      八十次赢、二十次亏，平均每笔还是亏的。原因不难找：每次亏的幅度是每次赚的五倍。
      <strong>胜率只是天平的一个托盘，不是判决书。</strong>
    </p>
    <p>
      再看一个用 R 记账的例子（独立示意）：胜率 50%，平均每笔盈利 2R，平均每笔亏损 1R，平均每笔摩擦成本 0.05R，
      同一公式逐步代入，得 E = 1.0R − 0.5R − 0.05R = +0.45R/笔；换成百分比口径再算一遍，结果一致。
    </p>

    <h3 id="c03-s3" class="sub-title" data-spy>三、胜率与盈亏比的跷跷板</h3>
    <p>
