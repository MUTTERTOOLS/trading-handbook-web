    <h3 id="c03-s4" class="sub-title" data-spy>四、E 大于零，只是一张门票</h3>
    <p>算出正的 E，值得高兴，但离"可以做"还远。原因有三层。</p>
    <p>
      <strong>第一层：成本会咬人。</strong>EX-F 里，0.2% 的成本把 +1.2% 削成 +1.0%，削掉了六分之一。
      交易越频繁，成本咬得越狠：毛利薄、次数多的做法，可能全给券商和税打了工（〔B2-C05〕算过全年账）。
      所以算 E 时成本项不能省，也不能故意用小数；宁可往大估，给自己留余量。
    </p>
    <p>
      <strong>第二层：E 是估出来的。</strong>四个输入都来自历史记账或统计，而历史是有限的样本。
      三十笔里赢了二十一笔（70%），未必代表真实水平，可能只是这一段运气好；样本要多少笔才够下结论，〔B6-C03〕给了具体的算法。
      市场环境也会变，过去的 E 不承诺未来的 E。
    </p>
    <p>
      <strong>第三层：赢了别人，还要赢过"不做"。</strong>就算 E 大于零而且可信，还要回答：比直接拿着宽基 ETF 不动强吗？
      比放在低风险资产里强吗？这就是与基准比较的问题，方法见〔B6-C10〕。一个策略忙一年，若还不如"什么都不做"，它的 E 再好看也说明不了价值。
    </p>
    <p>
      所以本章的结论是：<strong>E 大于零是必要条件，不是通行证。</strong>
      它的作用是把明显不合格的方法先筛掉，剩下的问题交给后面的册去回答。
    </p>
    <p>
      先给 E 定个位：它是平均数，不是路径。E 为 +0.45R 不等于每笔都赚 0.45R；真实过程是一串亏损与偶尔的大额盈利交错着走。
      E 为正的做法照样会接连几笔亏损，这在统计上完全正常；判断单笔看执行，判断一串结果才看 E。
    </p>

    <h3 id="c03-m" class="sub-title" data-spy>常见误区</h3>
    <Callout variant="warn" title="误区一：“胜率越高越好。”">
      <p>
        <strong>为什么错：</strong>EX-E 与 EX-F 对照已经说明：胜率 80% 可以亏钱，40% 可以赚钱。
        决定 E 的是胜率、盈亏比与成本的配平，不是任何单项。只盯胜率，会偏爱"赚小钱、亏大钱"的做法，恰是最危险的一类。
      </p>
      <p><strong>正确做法：</strong>每次评估都三个数一起看：胜率、盈亏比、成本；再查平衡表。胜率与赔率的配平深化，见〔B3-C08〕。</p>
    </Callout>
    <Callout variant="warn" title="误区二：“上一笔赚了说明方法对，上一笔亏了说明方法错。”">
      <p>
        <strong>为什么错：</strong>单笔结果被运气主导，一两次输赢几乎不携带信息；
        按这个习惯行事，人会今天换方法、明天加仓位，永远在追上一笔的结果。
      </p>
      <p><strong>正确做法：</strong>单笔只看执行：是否按事先写下的规则做了。方法好不好，要等积累了足够笔数、算出 E 与它的波动再判断（〔B6-C03〕讲要多少笔；亏损后如何归因见〔B7-C01〕）。</p>
    </Callout>
    <Callout variant="warn" title="误区三：“E 算出来是正的，就可以放心做了。”">
      <p>
        <strong>为什么错：</strong>E 大于零只是必要条件。样本可能太少、成本可能被低估、市场可能已变化，而且还没回答"比不做强不强"。
        把门票当通行证，是"回测漂亮、实盘亏钱"的第一步。
      </p>
      <p><strong>正确做法：</strong>把 E&gt;0 当作"值得继续研究"的信号，走完验证与基准比较〔B6-C10〕〔B6-C12〕，再考虑投入真实资金。</p>
