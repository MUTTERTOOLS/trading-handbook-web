    <h3 id="c02-s3" class="sub-title" data-spy>三、说不清来源，就不采信</h3>
    <p>五类来源摆在这里，不是为了背诵，而是为了当筛子用。检查一个方法，无论它来自书本、软件还是群聊，问三个问题：</p>
    <div class="formula-block">
      1. 这个方法赚的是谁的钱？（对应五类来源里的哪一类，或哪几类）<br />
      2. 对方为什么会持续把这笔钱让出来？（情绪、约束、需求差异，具体是什么）<br />
      3. 我凭什么比对方强？（数据、期限、理解、工具，具体说）
    </div>
    <p>
      <strong>来源三问</strong>全部答得上来，方法才进入"值得验证"的名单；任何一问答不上，无论故事多动听、截图多漂亮，都不采信。
      第三问尤其要诚实：大多数新手在这里没有答案，这是正常的起点——正因为没有现成的分析优势，新手更该从风险溢价这类"对手盘自愿付钱"的来源起步。
    </p>
    <p>
      拿一个常见说法把规则演示一遍："跌了这么多，总会涨回来的。"一问，赚谁的钱——答不上，它把"价格会回去"当成必然，说不清谁在付钱；
      二问，对方为什么持续让出——若"跌多了必涨"是稳定规律，早该被大量资金吃掉；三问，凭什么比对方强——答不上。三问全空，不采信。
    </p>
    <p>
      顺带把"不采信"说清楚：它不等于"肯定是骗局"，只代表"目前没有理由相信"。把这两者分开，避免从什么都信，滑到逢人就说骗子。
    </p>
    <p class="table-note">
      要强调两条界线。第一，答对三问不等于能赚钱：从"说得清"到"真赚到"之间，还隔着完整验证〔B6-C12〕与风控〔B3-C04〕。
      第二，具体策略属于后文的事：常见做法归为几个门派，在〔B8-C01〕展开；拆解卡把"收益来源"列为九个字段之一，见〔B8-C02〕。本章只给地图，不发路线。
    </p>

    <h3 id="c02-s4" class="sub-title" data-spy>四、这一章不能帮你做什么</h3>
    <p>四条边界，先说在前面。</p>
    <ol>
      <li>五类来源不是五条赚钱路线，只是地图上的五块地形。知道"风险溢价"这个词，不等于你拿着宽基 ETF 就稳了——波动可能持续很多年，这属于风控问题〔B3-C01〕。</li>
      <li>它不回答"现在哪块地形最肥"。来源是否存在、是否拥挤，要看数据，属于验证的事〔B6-C01〕。</li>
      <li>它不替代规则。从认知到下单之间还有整册的距离：市场规则〔B2〕与仓位风险〔B3-C04〕。</li>
      <li>它不替你完成诚实。来源三问的答案只有你自己能给，旁人无法替你回答第三问。把"说不出"如实记下来，比编一个像样的答案有用得多。</li>
    </ol>

    <h3 id="c02-m" class="sub-title" data-spy>常见误区</h3>
    <Callout variant="warn" title="误区一：“这个指标本身能赚钱。”">
      <p>
        <strong>为什么错：</strong>指标是观察工具，只负责描述盘面状态，不回答钱从哪来。
        一个金叉信号若说不出对手盘是谁、对方为什么持续让出价差，它就只是描述，不是收入来源。把工具当来源，是新手最常见的认知错位。
      </p>
      <p><strong>正确做法：</strong>先过来源三问，再谈工具好不好用。指标的构造与局限，后文〔B4-C01〕展开。</p>
    </Callout>
    <Callout variant="warn" title="误区二：“有人赚就有人亏，所以不可能赚。”">
      <p>
        <strong>为什么错：</strong>这句话把两笔账混成了一笔。价差博弈扣除费用后平均为负，没有错；
        但持有侧连着企业盈利增长，是正和，且五类来源里有几类的对手盘是自愿或被迫付钱，并非被"收割"。
        长期赚钱的人靠的是站在明确的来源上，不是靠运气碾压别人。
      </p>
      <p><strong>正确做法：</strong>分清自己赚的是哪一笔账、哪一类来源；答得出，才有资格谈"可能赚"。</p>
    </Callout>
    <Callout variant="warn" title="误区三：“来源说得清，这方法就靠谱了。”">
      <p>
        <strong>为什么错：</strong>来源三问是筛掉坏方法的必要检查，不是盖章放行。
        说清了来源，还可能败在样本太少、成本吃光利润、环境变化、执行走样。把"说得清"当"一定行"，会让人跳过验证直接上重仓。
      </p>
      <p><strong>正确做法：</strong>来源三问之后，走完整的验证流程〔B6-C12〕，并用小风险前向检验，而不是直接放大仓位。</p>
    </Callout>

