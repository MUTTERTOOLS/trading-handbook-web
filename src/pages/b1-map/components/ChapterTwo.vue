    <h3 id="c02-s2" class="sub-title" data-spy>二、五类收益来源</h3>
    <p>
      在负和的价差博弈里，为什么还有人长期赚钱。因为博弈之外还有正和的池子，而且对手盘的"输"各有各的结构，不是随机送钱。
      本丛书把常见的来源归为<strong>五类收益来源</strong>：风险溢价、行为偏差、制度与结构约束、流动性提供、分析优势。
      这个清单不保证穷尽，真实市场还有跨类的、更复杂的来源。
    </p>
    <p>每一类都回答同样三个问题：对手盘是谁；对方为什么会让出这笔钱；赚的到底是什么钱。逐类来看。</p>

    <div class="info-grid cols-2">
      <div class="info-card">
        <div class="ic-title">第一类：风险溢价</div>
        <p>
          <strong>类比：</strong>把房子租出去收租金。租金不是白拿的：你承担了空置、维修、租客拖欠的风险与麻烦。
          *类比的局限：*房租通常按年相对稳定，股价波动剧烈得多，补偿也不保证按期发放。
        </p>
        <p>
          <strong>风险溢价</strong>指承担了别人不愿承担的波动与不确定性，由此得到的补偿。
          对手盘不是某个具体的人，而是所有偏好安稳的资金：他们自愿用长期回报换安稳，不算"输"，只是长期合计少赚。
          赚的是承担波动的补偿，第一笔账里的企业盈利增长也归入这一类——同根，都要用时间和承担波动去换。
          <strong>怎么辨认：</strong>持有期长、标的分散、不依赖频繁操作。
        </p>
      </div>
      <div class="info-card">
        <div class="ic-title">第二类：行为偏差</div>
        <p>
          <strong>类比：</strong>打折季的商场。人群一起涌向某个柜台时，价格常常离谱：抢的时候贵得离谱，冷清的时候便宜得离谱。
          *类比的局限：*商场的情绪几天就散，市场的极端情绪可以持续数月甚至数年，"别人不理性"不等于"马上恢复理性"。
        </p>
        <p>
          <strong>行为偏差</strong>指人在金钱决策中系统性的、可重复的心理倾向：恐慌时贱卖、狂热时追高、跌久了不敢碰、涨久了不觉得贵。
          对手盘是被情绪推着走的交易者。他们输在时点——不是每笔都错，而是错得有规律，所以才可能被系统性地利用。
          赚的是对方在情绪化时点让出的价格差。<strong>怎么辨认：</strong>入场理由总离不开"别人都在慌"或"别人都在抢"。
        </p>
      </div>
      <div class="info-card">
        <div class="ic-title">第三类：制度与结构约束</div>
        <p>
          <strong>类比：</strong>急售的卖家。房主要搬家，必须在一个月内出手，于是接受明显低于心里的价——对面是一个"必须卖"的硬约束。
          *类比的局限：*急售不是每天都有，规模有限，而且"知道谁在急售、何时急售"需要合规的公开渠道，不能靠小道消息。
        </p>
        <p>
          <strong>制度与结构约束</strong>指某些资金因为规则、合同或期限，必须按既定时间和方式买卖，无法自由挑时机。
          对手盘的例子：按名单调仓的被动资金、面临赎回压力的基金、到达期限必须处置的账户。
          他们输的不是判断，而是身不由己；赚的是对方为"必须交易"付的成本。
          <strong>怎么辨认：</strong>机会集中在特定日期或规则附近，平时并不存在。
        </p>
      </div>
      <div class="info-card">
        <div class="ic-title">第四类：流动性提供</div>
        <p>
          <strong>类比：</strong>车站旁的换零钱摊。你想把一张整钱换成零钱，摊主帮你换，收一点小费——你买的是"马上能用"。
          *类比的局限：*摊主收的是确定的小费；市场里挂单的人可能收到烫手存货——价格快速变动时，刚接下的单子转眼就亏，小费未必盖得住。
        </p>
        <p>
          <strong>流动性提供</strong>指愿意先接下别人的单子、稍后再处理掉，从而赚取价差。
          对手盘是需要立即成交的人：急着进场的、急着出场的。他们不是输在判断，而是付钱买"马上成交"的便利——赚的就是这笔即时性的费用。
          <strong>怎么辨认：</strong>赚的是"马上成交"的对价，而不是方向判断的对错。
          提醒：这类玩法对速度、工具和成本控制要求极高，新手先了解即可，不作为起步方向。
        </p>
      </div>
      <div class="info-card" style="grid-column: 1 / -1;">
        <div class="ic-title">第五类：分析优势</div>
        <p>
          <strong>类比：</strong>买房前把一个片区的楼看了一遍，与住户、中介聊了一个月，通过公开渠道发现某条规划落地后的好地段。
          *类比的局限：*市场消化公开信息的速度远快于房产市场；你花一个月得出的发现，可能早已反映在价格里，也可能本身就是错的。
        </p>
        <p>
          <strong>分析优势</strong>指通过更准确的判断获得更好的结果。它有一个苛刻的前提：你能具体说出"凭什么比市场强"——
          是数据更准、理解更深，还是期限更长。说不出，这个优势就不存在，你的"分析"只是感觉。
