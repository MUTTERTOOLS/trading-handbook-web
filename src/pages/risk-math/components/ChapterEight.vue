    <h3 id="c08-s3" class="sub-title" data-spy>三、成本与频率：把及格线往上推的两只手</h3>
    <p>成本怎么动曲线？它动两端：盈利那头被削掉一块，亏损那头反被垫高一块。由此得到含成本的及格线：</p>
    <div class="formula-block">含成本盈亏平衡胜率 =（平均亏损 + 成本）÷（平均盈利 + 平均亏损）</div>
    <p><strong>打个比方。</strong>过桥要交固定的过桥费：运货赚了要交，没赚到也要交。来回一趟，赚的少一截，亏的多一截。</p>
    <p class="table-note"><em>类比的局限：</em>过桥费金额固定，交易成本随成交质量浮动（价差、滑点、冲击成本，见〔B2-C05〕），成交差时比费率本身更伤。</p>
    <p><em>算例一（EX-F 加成本，成本取 EX-P 的往返示意口径 0.2%，费率以〔B2-C05〕核验为准）：</em></p>
    <ul>
      <li>盈利端：6% − 0.2% = 5.8%</li>
      <li>亏损端：2% + 0.2% = 2.2%</li>
      <li>净盈亏比 = 5.8 ÷ 2.2 ≈ 2.64</li>
      <li>及格线 = 1 ÷（1 + 2.64）= 1 ÷ 3.64 ≈ 27.5%</li>
    </ul>
    <p>
      复算（直接代入公式）：（2 + 0.2）÷（6 + 2）= 2.2 ÷ 8 = 27.5%，两条路一致。
      再复算 E：0.4 × 5.8 − 0.6 × 2.2 = 2.32 − 1.32 = +1.0%/笔，与 EX-F 的结论一致。
    </p>
    <p>对照不计成本的 25%，计入成本后及格线上移 2.5 个百分点。同样方法推 EX-E 与 EX-G（成本 0.2%）：</p>
    <ul>
      <li>EX-E：（10 + 0.2）÷（2 + 10）= 10.2 ÷ 12 = 85%，实际胜率 80%，离线更远。</li>
      <li>EX-G：（8 + 0.2）÷（4 + 8）= 8.2 ÷ 12 ≈ 68.3%，实际胜率 65%，同样更远。</li>
    </ul>
    <p>一句话：成本让曲线上移，谁都躲不开。</p>
    <p>频率为什么也是配平项？它通过两个通道起作用。</p>
    <p><strong>通道一：成本按笔收，频率是它的放大器。</strong>EX-P 有一笔账：往返成本约 0.2% 时（示意口径），每周一次往返，一年 52 次，年损耗 = 52 × 0.2% = 10.4%。同样这套成本，每月一次往返一年只损耗 2.4%。方法没有变，变的只是频率，成本对账户的拖累差了四倍多。</p>
    <p><strong>通道二：高频率常伴小目标，小目标让成本显得大。</strong>看一个独立示意的对比。两个策略盈亏比同为 1.5：策略 A 平均盈利 6%、平均亏损 4%；策略 B 平均盈利 0.6%、平均亏损 0.4%（日内小额，目标近）。同样计入 0.2% 成本：</p>
    <ul>
      <li>策略 A：及格线 =（4 + 0.2）÷（6 + 4）= 4.2 ÷ 10 = 42%，比不计成本（1 ÷ 2.5 = 40%）只抬 2 个百分点。</li>
      <li>策略 B：及格线 =（0.4 + 0.2）÷（0.6 + 0.4）= 0.6 ÷ 1.0 = 60%，比不计成本抬了 20 个百分点。</li>
    </ul>
    <p>
      盈亏比相同，及格线一个抬 2 个点，一个抬 20 个点，差别只在目标远近。目标越近，0.2% 的成本在两端占的分量越大。
      这就是频率进入配平的原因：它决定成本是零头还是主角。
    </p>
    <p>
      还有两点补充。其一，本章的"成本"指回测口径的往返成本（含滑点假设），与〔B3-C04〕仓位公式里的"滑点缓冲"是两个口径，不要混用。
      其二，频率还有另一面——样本量：一年 100 笔比 12 笔更快看清一个方法，这属于验证话题，见〔B6-C03〕。
    </p>

    <h3 id="c08-s4" class="sub-title" data-spy>四、平均亏损会掩盖尾部亏损</h3>
    <p>
      先看一份统计（独立示意）。小刚做了 20 笔交易，每笔计划亏损 1,000 元（1R = 1%，按 EX-A 的 100,000 元本金口径）。
      事后逐笔记录实际亏损：18 笔按计划止损：各亏 1,000 元；1 笔滑点略大：亏 1,100 元；
      <strong>1 笔跳空低开，止损价未能成交：亏 5,000 元</strong>。
    </p>
    <p>逐步计算：</p>
    <ul>
      <li>实际总亏损 = 18 × 1,000 + 1,100 + 5,000 = 18,000 + 6,100 = 24,100 元</li>
      <li>实际平均亏损 = 24,100 ÷ 20 = 1,205 元</li>
      <li>实际平均亏损 ÷ 计划亏损 = 1,205 ÷ 1,000 ≈ 1.2</li>
    </ul>
    <p>
      只看平均值，结论是"每笔平均只超计划两成，执行还行"。但平均值把那笔 5,000 元摊薄成了每笔 250 元的存在感。
      真正值得警惕的信号——一笔 5R 的计划外亏损——被平均抹平了。
    </p>
    <p><strong>打个比方。</strong>一条平均水深 1.2 米的河，走过中心的人也可能被 2 米的深坑淹到。平均数描述的是摊平之后，而人淹水发生在最深的那一点。</p>
    <p class="table-note"><em>类比的局限：</em>河的深浅是空间分布，站在浅处就安全；交易的尾部亏损在时间上无法预知，躲不开，只能靠事前规则限制单笔敞口。</p>
    <p>
      给两个词下定义。<strong>尾部亏损</strong>：偏离平均值很远的少数极端亏损，常见来源是跳空、一字跌停、停牌，或未按规则退出。
      <strong>实际/计划亏损比</strong>：实际平均亏损 ÷ 计划亏损，衡量计划亏损被现实打穿的程度（〔B7-C07〕把它列入月度统计）。
    </p>
