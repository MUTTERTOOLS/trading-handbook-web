    <h3 id="c08-m" class="sub-title" data-spy>常见误区</h3>
    <Callout variant="warn" title="误区一：“胜率高就代表方法好，我先看胜率再看他亏多少。”">
      <p>
        <strong>为什么错：</strong>胜率只是配平三量之一，脱离盈亏比没有意义。EX-E 胜率 80%，E 仍为 −0.4%/笔。
        网格类方法的高胜率来自"每格小赢、偶尔深亏"的结构，胜率高是结构产物，不等于优势。
      </p>
      <p><strong>正确做法：</strong>先算统计口径盈亏比与及格线，再看实际胜率是否高出线，计入成本后是否仍然高出。</p>
    </Callout>
    <Callout variant="warn" title="误区二：“我的平均亏损只超计划两成，执行得不错。”">
      <p>
        <strong>为什么错：</strong>平均数会摊薄尾部。20 笔里一笔 5R 的计划外亏损，在平均值里只体现 0.25R；
        如果那笔是停牌复牌造成的 20R，平均值依然好看，账户已经重伤。
      </p>
      <p><strong>正确做法：</strong>平均值、单笔最大实际亏损、触发原因三项一起看。单笔超过 3R（独立示意线）必须逐笔复盘。</p>
    </Callout>
    <Callout variant="warn" title="误区三：“盈亏比 1.2，胜率 45% 就够，这条线很容易站住。”">
      <p>
        <strong>为什么错：</strong>三处站不住。其一，盈亏比 1.2 的及格线 = 1 ÷ 2.2 ≈ 45.5%，45% 还差一点。
        其二，这是不计成本的线，含成本后更高。其三，胜率统计本身有估计误差，30 笔样本下真实值可能偏离十几个百分点（EX-L）。
        贴线的方法，任何小扰动都会把它压到线下。
      </p>
      <p><strong>正确做法：</strong>按含成本公式算及格线，要求实际胜率留出明显余量；样本不足时，把"不确定"当作"没过线"处理。</p>
    </Callout>

