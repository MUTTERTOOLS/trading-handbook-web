        一次正常的市场回撤，就可能撞上一次正常的生活支出。
      </p>
      <p><strong>正确做法：</strong>按分层表逐项列出支出，扣除备用金与 1 年内需求，剩余才是可入市资金。</p>
    </Callout>
    <Callout variant="warn" title="误区二：“定投是长期策略，钱放进去就行，随时要用随时取。”">
      <p>
        <strong>为什么错：</strong>定投会摊低成本，但仍可能长期浮亏，需资金期限匹配。
        取出那天若恰在浮亏中，浮亏就变成实亏（本章第二节的算例）。
        "长期策略"不仅不提供"随时可取"的能力，反而要求最长的期限。
      </p>
      <p><strong>正确做法：</strong>入市前确认这笔钱 5~10 年内不用（起步参考值，需个人校准），并给生活急用排好顺序：先用备用金，再动 1 年内需求层，最后才考虑动市场里的钱。</p>
    </Callout>
    <Callout variant="warn" title="误区三：“就借这一次，下个月工资一到就还上。”">
      <p>
        <strong>为什么错：</strong>还款日与市场的节奏无关，浮亏没有等待的权利；价格不动也要付利息，亏损再多一层。
        何况要不要借，应当在冷静时由规则决定，而不是在缺钱时由急迫决定。
      </p>
      <p><strong>正确做法：</strong>钱不够就缩小投入或推迟开始；第三层为零时先攒层。市场不会关门，还款日不会商量。</p>
    </Callout>

