      资金用途也受合同约束，投入股市一般既违约又违规【待核验】。还款日被拆成每月一次，等于每个月都有一个小的"强制离场日"。
      至于"借钱买货币基金赚利差"：货币基金收益不固定，通常也低于借款利率（定性），利差为负是常态，这条路不通。
    </p>

    <h3 id="c11-s4" class="sub-title" data-spy>四、解禁条件：从"禁止"到"可以研究"</h3>
    <p>零杠杆是新手阶段的规则，不是终身判决。但解禁不靠时间，也不靠信心，靠两个条件同时满足。</p>
    <p><strong>解禁条件</strong>：解除零杠杆禁令须同时满足的两个条件——完整验证记录，与一次完整的熔断复盘。</p>
    <p>
      <strong>条件一：完整验证记录。</strong>杠杆只能加在"一个被验证过的方法"上，不能加在"一种感觉"上。
      完整验证记录指：方法已按九步验证清单走完全流程（后文〔B6-C12〕详述），证据强度达到 A 级或 B 级（后文〔B6-C04〕详述），
      回测计入成本并给出回撤与连亏分布，且完成了前向小资金实盘（起步参考值 30~50 笔，低频策略按 6~12 个月，需个人校准；后文〔B6-C11〕详述）。
    </p>
    <p>
      <strong>条件二：一次完整的熔断复盘。</strong>在零杠杆状态下，完整经历过一次"回撤触及熔断线 → 停手 → 排查 → 复工"
      （见〔B3-C10〕）。为什么必须亲历一次：熔断复盘能给出验证报告给不了的两样东西——回撤的真实体感，以及压力之下自己真实的行为记录。
      没有经历过深回撤的人，几乎都会高估自己的承受力，而"以为自己扛得住"恰恰是加杠杆前最常见的一句话。
    </p>
    <p>
      两个条件都满足之后，解禁的也只是"可以研究杠杆"，不是"应该使用杠杆"。
      是否使用，要看方法是否真的需要，并回到账户硬上限 H（见〔B3-C10〕）重新推算约束。
      许多长期存活的老手终生零杠杆，零杠杆不是缺陷。
    </p>
