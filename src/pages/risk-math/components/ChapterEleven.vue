    <h3 id="c11-s3" class="sub-title" data-spy>三、零杠杆禁令：为什么新手一分杠杆都不能碰</h3>
    <p>
      第三层资金进入账户后，会不断遇到诱惑："融资利息不高""期货双向都能赚""消费贷利率低，可以套利差"。
      本节把禁令一次讲全。<strong>零杠杆禁令</strong>：新手阶段不使用任何杠杆工具、不借钱投资的强制规则。
      它是六条风控骨架的第四条，禁令细则的归属章就是本章。
    </p>
    <p>禁令覆盖四件事：</p>
    <ol>
      <li>不使用融资融券、期货、期权等自带杠杆或保证金的工具（期权卖方风险尤大）。机制与风险演示详见〔B2-C07〕，此处只禁不讲。</li>
      <li>不参与场外配资。它不仅风险失控，还不受法律保护，常与骗局相连（〔B2-C08〕）。</li>
      <li>不借钱投资，包括向亲友借款和民间借贷。</li>
      <li>不用信用卡、消费贷资金投资。</li>
    </ol>
    <p>
      第 1 类工具的风险，按归属划分一句带过：2 倍杠杆下标的跌 10%，本金亏 20%；5 倍杠杆下本金亏 50%，利息另计
      （EX-N；机制与数字演示见〔B2-C07〕）。
    </p>
    <p><strong>为什么新手必须零杠杆，理由有三。</strong></p>
    <p>
      <strong>理由一：新手不知道自己的期望是正是负。</strong>
      期望公式（〔B1-C03〕）需要胜率、盈亏比与成本三个输入，它们只能从验证与记录中来。
      没有验证记录的方法，期望未知，而杠杆把一个未知数放大。亏损那一侧还有回本表在等着：
      亏 20% 需涨 25%，亏 50% 要翻倍（EX-H）。杠杆的作用，是把本可能只是普通回撤的波动，推进这张表的深处。
    </p>
    <p>
      <strong>理由二：杠杆把资金期限的钥匙交给别人。</strong>
      融资融券有利息，按占用天数累积，利率区间见〔B2-C07〕【待核验】。价格不涨不跌，利息也在增长，
      杠杆账户里，时间默认站在你的对面。融资账户还设有担保要求，账户资产跌到约定水平时，会被要求补足或强制卖出
      （机制见〔B2-C07〕，具体比例【待核验】）。也就是说，卖出时点可能由规则替你决定，你写好的退出规则可能根本轮不到执行。
      借钱投资同理：还款日就是别人给你定的"强制离场日"。
    </p>
    <p><strong>理由三：还款日不由你选。</strong>（本例为独立示意）</p>
    <p>小王自有 50,000 元，又借入 50,000 元，约定一年后一次还本付息，利息共 4,000 元。他把 100,000 元全部买入乙 ETF。到期日三种情形：</p>
