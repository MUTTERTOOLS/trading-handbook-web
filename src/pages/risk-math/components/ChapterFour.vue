    <h3 id="c10-s3" class="sub-title" data-spy>三、硬上限 H 与熔断线：给账户装一只空气开关</h3>
    <p>画回撤线需要两个数。第一个是绝对天花板。</p>
    <p>
      <strong>硬上限 H</strong>：账户总回撤的强制停手线。本书起步参考值为 <strong>15%</strong>（可取 12%~15%），需个人校准。
    </p>
    <p>
      为什么放在 15% 这个量级：按〔B3-C01〕的公式，亏 15% 回本需涨约 17.6%（0.15 ÷ 0.85 ≈ 0.176），仍在浅水区。
      对照 EX-H 回本表，亏 30% 要涨约 42.9%，深水区的修复难度完全不同。
      H 的作用是：无论策略发生什么，账户都不被允许滑进深水区。
    </p>
    <p>但 H 只封顶，不管日常。如果熔断线每次都贴着 H 画，正常坏运气就会反复顶到天花板，停手会变成常态。误报问题由第二个数解决。</p>
    <p>
      <strong>熔断线</strong>：min（回测高分位最大回撤 × 1.5，硬上限 H）。
      触发后停止开新仓，已有持仓按事先写好的规则减仓或清仓（七种合法退出中的第 6 种，〔B3-C09〕）。
    </p>
    <div class="formula-block">熔断线 = min（回测高分位最大回撤 × 1.5，硬上限 H）</div>
    <p><strong>打个比方。</strong>家里的空气开关：电流超过限值，它自动跳闸，断开线路。装它不是为了每天跳着玩，而是为了让"超限"这个事件有一个自动的、无争议的动作。</p>
    <p class="table-note">*类比的局限：*空气开关跳闸基本等于线路确有问题；熔断线被触发却可能只是正常方差走到了尾部。所以熔断之后要先排查（第五节），不能直接判定策略已坏。</p>
    <p>公式里两个部件各管一件事：</p>
    <ol>
      <li>
        <strong>乘 1.5 解决误报。</strong>如果熔断线恰好画在 99 分位回撤上，最坏的 1% 运气会全部触线。
        乘 1.5 之后，触线要求回撤比 99 分位还远得多，触线才更可能意味着"跑出了分布"。1.5 是熔断倍数，起步参考值，需个人校准。
      </li>
      <li>
        <strong>取 min 解决"策略配不上账户"。</strong>如果高分位回撤 × 1.5 已经超过 H，说明单笔风险相对账户太大，
        问题不在画线，在风险本身。下一节先降风险，再回来画线。熔断线绝不允许高于 H。
      </li>
    </ol>
    <p>
      还有一个口径提醒：回撤从净值历史高点算起。账户完全可能在"还赚着"的状态下触线。
