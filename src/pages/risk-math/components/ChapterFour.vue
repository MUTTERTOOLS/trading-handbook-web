    <h3 id="c10-m" class="sub-title" data-spy>常见误区</h3>
    <Callout variant="warn" title="误区一：“回撤到了就该换策略。”">
      <p>
        <strong>为什么错：</strong>触线只说明回撤到达了停手线，不说明原因。三类归因没查完就换策略，有两种常见代价：
        若是执行偏差，换策略后偏差照旧；若是正常方差（设计上允许的尾部情形），等于扔掉没病的方法，还要从零攒样本（样本量与标准误见〔B6-C03〕）。
        频繁换策略的人，永远没有足够样本判断任何一个方法。
      </p>
      <p><strong>正确做法：</strong>触线 → 停手 → 按心、时、策略顺序排查 → 写下书面结论 → 复工或停用（〔B6-C11〕）。</p>
    </Callout>
    <Callout variant="warn" title="误区二：“熔断后赶紧回本，把单笔风险调大一倍，赚快一点。”">
      <p>
        <strong>为什么错：</strong>回本压力用错了算术。亏 9% 只需涨约 9.9% 就能回本（0.09 ÷ 0.91 ≈ 0.099，按〔B3-C01〕公式），并不急。
        而把单笔风险从 0.5% 提到 2%，回撤近似放大 4 倍：原来约 6% 的 99 分位回撤变成约 24%，反推条件（×1.5 ≤ H）被破坏。
        若继续放大到单笔 5% 的量级，连亏 7 笔回撤约 30.2%（EX-I），要涨约 43% 才回本（EX-H）。急着回本是滑向深亏最常见的路径之一。
      </p>
      <p><strong>正确做法：</strong>熔断后按复工条件走。过渡期风险只降不升，恢复原值前清单必须全部通过。</p>
    </Callout>
    <Callout variant="warn" title="误区三：“熔断线太钝了，我再加一条‘连亏 5 次就停’，双保险。”">
      <p>
        <strong>为什么错：</strong>EX-R 显示，胜率 40% 的策略 100 笔期望最长连亏约 7 笔，连亏 5 次属于正常波动。
        这条"保险"会频繁误触发，最后要么被废弃，要么把注意力从真正的线上引开。
        规则越多越难全部执行，违规率反而上升（违规分级与目标见〔B7-C09〕）。
      </p>
      <p><strong>正确做法：</strong>停手只用回撤一条线（熔断线）；连亏只作为排查时的参考信息，不作为触发条件。</p>
    </Callout>

