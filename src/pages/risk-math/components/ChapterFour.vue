    <h3 id="c10-s4" class="sub-title" data-spy>四、反推仓位：让正常波动够不着熔断线（EX-K）</h3>
    <p>
      熔断线的设计目标是：<strong>正常波动（99 分位回撤）够不着线。</strong>
      如果够得着，不改公式，而是先把单笔风险降下来。这里用到一个近似关系：回撤与单笔风险比例近似成正比。
      单笔 1% 时 99 分位回撤 12%，单笔 0.5% 就近似 6%。
    </p>
    <p>全丛书统一算例 EX-K 完整走一遍：</p>
    <ol>
      <li>
        <strong>步骤 1：</strong>回测加随机重排模拟给出：单笔风险 1% 时，策略 99 分位最大回撤为 12%（统一算例的结论性数字；得到它的方法见〔B6-C09〕）。
      </li>
      <li><strong>步骤 2：</strong>检验反推条件：12% × 1.5 = 18%，18% &gt; H = 15%，<strong>不通过</strong>。如果硬画，熔断线将高于天花板，不允许。</li>
      <li><strong>步骤 3：</strong>反推单笔风险上限：需要 12% × 1.5 × x ≤ 15%，解得 x ≤ 15% ÷ 18% ≈ 0.83%。现有单笔风险 1% 必须降。</li>
      <li><strong>步骤 4：</strong>取整到更低一档：取 0.5%（起步参考值 0.5%~1% 的低档；降风险取低不取高）。</li>
      <li><strong>步骤 5：</strong>重算回撤：99 分位回撤 ≈ 12% ×（0.5 ÷ 1）= 6%；6% × 1.5 = 9% ≤ 15%，<strong>通过</strong>。</li>
      <li><strong>步骤 6：</strong>写下熔断线：min（9%，15%）= <strong>9%</strong>。</li>
    </ol>
    <p>这套流程与〔B3-C03〕的五步顺序是同一种思路：先定"最多可以亏多少"，再让策略参数去配它，而不是反过来。</p>
