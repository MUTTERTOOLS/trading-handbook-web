    <h3 id="c10-s5" class="sub-title" data-spy>五、触发之后：排查顺序与复工条件</h3>
    <p>先写触发当天的动作，全部来自事前规则：</p>
    <ol>
      <li>停止开新仓；</li>
      <li>已有持仓按事先写好的规则处理（减仓或清仓，〔B3-C09〕）；</li>
      <li>不加杠杆，不临时改规则，不为了"捞回来"继续交易（零杠杆见〔B3-C11〕）。</li>
    </ol>
    <p>
      然后进入排查。排查顺序固定：<strong>心 → 时 → 策略</strong>，对应执行偏差、环境变化、策略失效三类归因；
      "正常方差"是排查后允许出现的第四种结论。三类归因的完整诊断方法属〔B7-C01〕，这里只给顺序和动作。
    </p>
    <p>
      <strong>第一步查心（执行偏差）。</strong>对照交易记录逐笔检查：有没有没按规则做的动作，比如漏单、迟入、早走、扛单、违规加仓、超仓
      （偏差类型与影子账户的核对方法见〔B7-C04〕）。如果触线主要由执行偏差造成，问题在执行层，不在策略层，修复动作也应落在执行层。
    </p>
    <p>
      <strong>第二步查时（环境变化）。</strong>问一个问题：策略赚钱依赖的前提还在吗。比如依赖趋势的市场是否已经长期震荡，依赖流动性的标的是否量能消失。
      这里要用的是<strong>环境过滤器</strong>：事先写进规则的、依据市场状态调整总仓位或单笔风险的条件（详见〔B7-C05〕）。
      注意：过滤器是事前规则，在触线之前就运行；回撤之后临时降仓不是过滤器，是事后情绪反应。
    </p>
    <p>
      <strong>第三步查策略（策略失效）。</strong>若执行无偏差、环境未见明显变化、回撤仍明显超出分布，策略的逻辑前提可能被破坏，进入停用评估。
      停用判据（含"回撤触及熔断线"这一条）见〔B6-C11〕。
    </p>
    <p>
      排查可能出现第四种结论：按规则执行、环境未变、回撤只是走到了分布的尾部，即正常方差。
      这个结论允许存在，这也正是熔断线乘 1.5 之后仍可能触线的原因：尾部没有被截断。
    </p>
    <p>
      <strong>分布内不缩仓。</strong>回撤没有触线、或排查结论为正常方差时，恢复原风险交易，不因疼痛而永久缩仓。
      理由有二：其一，临时缩仓是未经验证的规则变更；其二，"亏了缩、新高了放大"会让仓位变大在高位、变小在低位，等于在自己的净值上追涨杀跌。
      接近熔断线时的日常行为清单属〔B7-C06〕。
    </p>
    <p><strong>复工条件</strong>：熔断触发后，恢复原风险交易之前必须满足的书面条件。没有清单，"复工"会退化成"手痒"。起步模板如下（需个人校准）：</p>
