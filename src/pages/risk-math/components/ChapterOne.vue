    <h3 id="c01-m" class="sub-title" data-spy>常见误区</h3>
    <Callout variant="warn" title="误区一：“亏了没关系，涨回来就行。”">
      <p>
        <strong>为什么错：</strong>三层。第一，回本难度被低估：亏 50% 要涨 100%，亏 90% 要涨 900%（EX-H）。
        第二，回本期间在付时间成本：按"每年恰好 +10%"的纯假设，亏 50% 也要等约 8 年。
        第三，"等涨回来"不是一个退出规则，它没有触发条件、没有时间限制；深亏之后临时改口"我拿长线"，是典型的顺序颠倒（〔B3-C03〕）。
      </p>
      <p><strong>正确做法：</strong>亏损的上限和处理动作在买入前写好；浅亏按规则执行，深亏按规则评估，而不是默认"等"。</p>
    </Callout>
    <Callout variant="warn" title="误区二：“小亏无所谓，何必动不动就卖。”">
      <p>
        <strong>为什么错：</strong>这句话混淆了两种"小亏"。<strong>计划内亏损</strong>是买入前就定好上限的亏损，它是交易的成本，确实无关紧要。
        <strong>计划外亏损</strong>是没写规则、还没按规则处理的亏损——扛着不管，小亏会滑向深亏，而深亏按回本表加速变贵。
        前者怎么定义见〔B3-C04〕；后者正是〔B3-C02〕中"扛单"这种破产结构的常见起点。
      </p>
      <p><strong>正确做法：</strong>先有书面规则，再谈"无所谓"。没有规则的"小亏"不是成本，是还没长大的大亏。</p>
    </Callout>
    <Callout variant="warn" title="误区三：“平均每年赚 15%，滚十几年就是大数字。”">
      <p>
        <strong>为什么错：</strong>把算术平均当成了几何平均。波动越大，真实复利被拉低得越多：本章路径二算术平均约 16.7%，
        几何平均只有约 4.0%；路径三算术平均为正，终值反而亏 24.4%。
      </p>
      <p><strong>正确做法：</strong>一律看复利净值曲线和回撤深度（停手规则见〔B3-C10〕；方法验证本身属后文〔B6-C12〕范围）。</p>
    </Callout>

