    <h3 id="c05-m" class="sub-title" data-spy>常见误区</h3>
    <Callout variant="warn" title="误区一：“止损就是我能承受的亏损线，我能亏 5% 就设 5%。”">
      <p>
        <strong>为什么错：</strong>"能亏多少"回答的是预算（1R），"在哪里失效"回答的是止损价，两者不是一回事。
        承受线定的止损随入场价漂移：10.80 元买入时，5% 止损挂在 10.26 元，比失效点 9.50 元还高 0.76 元——逻辑没坏，人已出局。
        它也不看波动：对日均 5% 的 X，5% 的距离一个正常波动日就可能触发。
      </p>
      <p><strong>正确做法：</strong>止损价从失效点找（结构位、ATR 余量），承受线只进公式左边当 1R，股数由公式反推（〔B3-C04〕）。</p>
    </Callout>
    <Callout variant="warn" title="误区二：“每只股票统一设 5% 就行。”">
      <p>
        <strong>为什么错：</strong>统一比例无视波动差异。同样 5%（距离 1 元）：对 X 是 1×ATR，太紧，易被日常波动打掉；
        对 Y 是 10×ATR，太宽，仓位被压小，逻辑失效后要滑很远才触发。一把尺子量所有股票，必然一半太紧、一半太宽。
      </p>
      <p><strong>正确做法：</strong>位置用结构定，宽度用 ATR 校准；固定比例只用于不看图的极简场景或兜底硬线（起步参考值，需个人校准）。</p>
    </Callout>

