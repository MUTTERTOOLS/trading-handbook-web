    </p>
    <p class="table-note">*类比的局限：*保险丝熔断没有成本，止损触发是真金白银的亏损；电器可以换，买入逻辑对应的市场结构不能换。</p>
    <p>
      <strong>买入逻辑失效点</strong>：价格到达后，当初买入的理由不再成立的位置。
      买入逻辑是"站稳前期低点之上"，失效点就是跌破该低点；买入逻辑是"突破盘整区后延续"，失效点就是跌回盘整区。
    </p>
