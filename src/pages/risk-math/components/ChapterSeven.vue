    <h3 id="c05-s1" class="sub-title" data-spy>一、止损价从哪里来：先找失效点</h3>
    <p>
      <strong>先看一个对比。</strong>小张和小李都要买 10.00 元的甲股份，止损都设在 9.50 元。
      小张的理由是"我最多接受亏 5%"；小李的理由是"前期低点在 9.50 元，跌破它，'站稳低点之上'的买入理由就不成立了"。
    </p>
    <p>换个入场价，差别立刻出现。假设小张追高，在 10.80 元买入（示意）：</p>
    <ul>
      <li>
        小张：止损 = 10.80 × 95% = 10.26 元，仍在前期低点上方。价格跌到 10.26 元时，失效点还没到，逻辑没被推翻，
        他却因"亏到 5%"先出局了。
      </li>
      <li>
        小李：止损仍是 9.50 元。失效点不随入场价移动；入场价高了，止损距离变长，股数相应变小——怎么变小，由〔B3-C04〕的公式管。
      </li>
    </ul>
    <p>
      两个问题各管各的：<strong>"我能亏多少"决定 1R，"逻辑在哪里失效"决定止损价。</strong>
      1R 是预算，止损价是触发条件。把预算当成触发条件，止损就会跟着入场价漂移，与逻辑脱钩。
    </p>
    <p>
      <strong>打个比方。</strong>保险丝的规格由电线的承载能力决定，不是由你想带动多大的电器决定。
