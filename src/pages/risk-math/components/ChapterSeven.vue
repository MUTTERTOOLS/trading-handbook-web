    <h3 id="c07-s3" class="sub-title" data-spy>三、四个抓手：找出同一个托盘</h3>
    <p>
      新手不需要算相关系数，只需要回答一个问题：哪几笔持仓，会被同一条新闻、同一股资金、同一次风格切换一起打中？
      实务里有四个抓手。逐笔检查，命中任何一条，就归入同一组。
    </p>
    <p><strong>抓手一：同行业。</strong>主营业务相同，或处在同一条产业链上。一条行业政策、一次原料涨价，会同时改变它们的盈利预期。两家整车厂平时走势可以很不同步，行业利空一来却会一起承压。</p>
    <p><strong>抓手二：同主题。</strong>行业不同，但被市场编进同一个故事。题材情绪来的时候一起涨，退的时候一起跌。比如一家做软件、一家做电机，只因同属某个热门题材，就可能同涨同跌。</p>
    <p><strong>抓手三：同风格。</strong>市场还会按"大小、贵贱、波动高低"给股票分组。风格切换那天，同风格的股票常常被一起卖出，哪怕行业互不相干。一批小市值、高波动的股票，就是这样一个隐性组。</p>
    <p><strong>抓手四：同指数成分。</strong>同属一个指数的成分股，会被跟踪该指数的资金按同一份名单买卖，涨跌容易被指数这台"发动机"带着走。</p>
    <p>
      看一个分组示意（独立示意）。某账户有八笔持仓：子、丑、寅都是整车厂；卯是轮胎厂，与三家同处一条产业链；
      辰、巳行业不同，但被市场归入同一个热门题材；午是小市值、高波动股；未是宽基 ETF。
      按四个抓手：子丑寅卯归入"产业链组"，辰巳归入"题材组"，午归入"小盘风格组"，未记入"宽基组"。
      八笔持仓，四个组——组合风险按组管理，而不是按八只管理。
    </p>
    <p>三条使用规则：</p>
    <ol>
      <li><strong>逐笔过一遍四个抓手，命中任何一条即同组。</strong>拿不准时按同组处理，宁可从严。</li>
      <li><strong>四个抓手会重叠。</strong>一只股票可以同时命中三条，归入一个组即可，不必重复计算。</li>
      <li><strong>分组不是不让买。</strong>同一组可以有多笔持仓，但整组要按下一节的合并口径过校验。</li>
    </ol>
    <p class="table-note"><em>类比的局限（对四个抓手整体）：</em>抓手是检查表，不是精确度量。它回答"有没有可能一起动"，回答不了"会一起动多少"。幅度要靠坏情形假设，下一节展开。</p>

    <h3 id="c07-s4" class="sub-title" data-spy>四、同板块合并计算：EX-O 全程</h3>
    <p>
      <strong>同板块合并计算</strong>，是把同一组的持仓当作一笔来校验风险的规则：整组算一个组风险，与组外持仓分开列示、分别对照上限。
      操作只有三步。
    </p>
    <p><strong>第一步：分组。</strong>用四个抓手把持仓分成若干组，列出每组成员与合计仓位。单独一只股票也算一组，组内只有它自己。</p>
    <p>
      <strong>第二步：给每组定一个坏情形幅度。</strong>也就是"一件事打过来，这一组平均会跌多少"的估计。
      对单只股票，它就是〔B3-C06〕的最坏跳空亏损估计；对一组，可参考组内个股的最坏跳空，取平均或偏大值。
      这是估计值，没有统一标准，需保守自定并记进登记表。
    </p>
    <p><strong>第三步：校验。</strong></p>
    <div class="formula-block">
      组风险 = 组合计仓位 × 组坏情形幅度<br />
      在途总风险（合并口径）= 各组组风险之和
    </div>
    <p>
      合并口径与计划口径都要 ≤ 上限（起步参考值 5%，需个人校准）。
      计划口径默认"止损都正常工作"；合并口径假设"一件事把一组的止损全部打穿"。
    </p>
    <p>
      先把规则用在开仓之前。假设小明只持有 W 板块的甲、乙、丙、丁四只，各 15%，合计仓位 60%。
      此时出现第五只戊股份，也想买 15%。查组预算：按 −8% 估坏情形，现有组风险 = 60% × 8% = 4.8%，已贴近 5% 上限；
      再加 15%，变成 75% × 8% = 6.0%，必定超限。所以戊股份不能按 15% 开。
      可选的做法：减持组内旧仓腾出预算、把新仓位改小到预算装得下，或者放弃。
      <strong>合并口径的价值正在于此：它把"每一单看都合规、合起来超限"的机会，拦在下单之前。</strong>
    </p>
    <p>下面用全丛书统一算例 <strong>EX-O</strong> 走完全程。</p>
    <p>
      <strong>背景。</strong>本金 100,000 元（EX-A 口径）。五只虚构标的同属一个行业板块。
      每只买入 15,000 元，各占本金 15%，总敞口 75%。每只止损设在买入价下方 5%（本章为展开 EX-O 补充的示意设定）。
    </p>
    <p><strong>第一步：每只单独看，都合规。</strong>单票上限 15% ≤ 20%，通过；每笔计划亏损 = 750 元（0.75%）；
    五笔合计 3,750 元，计划口径 = 3.75% ≤ 5%，通过。</p>
    <p><strong>第二步：合并分组。</strong>五只同行业，命中抓手一，全部归入 W 组。组合计仓位 = 75%。</p>
    <p>
      <strong>第三步：合并口径校验。</strong>行业利空，平均跳空 −8%（EX-O）。止损设在 −5% 处，跳空直接越过止损价，五道止损同时失灵。
      每只亏损占本金 = 15% × 8% = 1.2%；W 组风险 = 75% × 8% = <strong>6.0%</strong>。
      复算：75,000 × 8% = 6,000 元；6,000 ÷ 100,000 = 6.0%。
    </p>
    <div class="callout callout-danger">
      <div class="callout-title">6.0% &gt; 5%，超限</div>
      <p>
        每一只都符合单票上限，计划口径也合规，问题出在五只其实是一注。合并之后，W 组等价于一笔 75% 仓位的"板块大仓"。
        一条行业新闻就能同时打中全部成员。在相关性高的组合里，"同时触发止损"不是小概率，而是行业利空日的常态。
      </p>
      <p>顺带说一句：同涨同跌也包括一起涨。五笔持仓一起涨的日子，容易让人误以为分散有效；检验分散的，从来是坏日子。</p>
    </div>
    <p><strong>超过上限怎么办。</strong>分两种情况。已经持仓的，有三条路：</p>
    <ol>
      <li>
        <strong>减持该组。</strong>如果想把单一板块的组风险控制在 3% 以内（把 5% 总预算的一部分划给一个板块，此处 3% 为独立示意），
        那么组合计仓位 ≤ 3% ÷ 8% = 37.5%。五只各降到 7%，合计 35%，组风险 = 2.8%，回到预算之内。
      </li>
      <li><strong>换标的。</strong>把其中一两只换成不同板块的标的，或换成宽基 ETF，让 W 组变小。</li>
      <li><strong>立一条规矩。</strong>该组预算已满，此后同板块的新机会一律不开，等组内某笔离场腾出额度。</li>
    </ol>
    <p>
      还没开仓的，规则只有一条：先查登记表里这个标的属于哪一组，组预算装不下就不开。
      同板块的新机会再好，也等离场或缩小到装得下为止。
      这与〔B3-C04〕"不能因为机会太好就破例"是同一条纪律，只是从单笔搬到了组。
    </p>
    <p><strong>一句话总结：相关性不改变单笔的算法，改变的是"几笔合起来算一笔"。</strong></p>

    <h3 id="c07-s5" class="sub-title" data-spy>五、持仓登记表：把组合风险摆到纸面上</h3>
