    <h3 id="c07-m" class="sub-title" data-spy>常见误区</h3>
    <Callout variant="warn" title="误区一：“我买了 10 只股票，足够分散了。”">
      <p>
        <strong>为什么错：</strong>分散看的是托盘，不是鸡蛋数量。10 只里若有 6 只同板块，合并后那是一笔大仓。
        EX-O 里五只各 15%，看似分散，一次行业利空合计亏 6%，超过 5% 上限。
        数量多还有另一个代价：每只的研究、记账、复盘都被摊薄，等于哪一只都管不好。
      </p>
      <p><strong>正确做法：</strong>用四个抓手分组，同板块合并计算。分散的目标是"不同时亏钱"，不是"名字多"。宁可五只分属不同组的持仓，不要十只挤在两个托盘里。</p>
    </Callout>
    <Callout variant="warn" title="误区二：“ETF 一定是分散的。”">
      <p>
        <strong>为什么错：</strong>分不分散，看它跟踪什么。宽基 ETF 跨行业、成分数量多，分散度较高。
        行业 ETF、主题 ETF 的成分全是同一板块的股票，涨跌高度同步——在合并口径下，它就是"一笔板块仓位"，
        还要与手里该板块的个股合并计算。买一只行业 ETF，再加两只同行业个股，等于把托盘换成了更大的托盘。
      </p>
      <p><strong>正确做法：</strong>买入前先看跟踪的指数。宽基 ETF 单独记一组；行业 ETF、主题 ETF 计入对应板块组，与个股合并校验。</p>
    </Callout>
    <Callout variant="warn" title="误区三：“每笔都过了六步走，组合就不会有大亏。”">
      <p>
        <strong>为什么错：</strong>六步走的第 6 步只把各笔计划亏损加总，那是计划口径。
        它没有回答"几笔会不会被同一个原因同时打穿"。相关性高的组合，合并口径会比计划口径大得多：EX-O 从 3.75% 变成 6.0%。
        个体都合规，整体仍可能超载，就像十辆合规的卡车可以压垮一座桥。
      </p>
      <p><strong>正确做法：</strong>在六步走之外增加合并口径校验；用持仓登记表管理各组预算；组满之后，同板块新机会一律不开或缩小。</p>
    </Callout>

