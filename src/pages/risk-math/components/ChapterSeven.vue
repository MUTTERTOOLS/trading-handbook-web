    <h3 id="c05-s2" class="sub-title" data-spy>二、三种设置法：结构位、ATR、固定百分比</h3>
    <p><strong>方法一：结构位止损——管"放在哪"。</strong></p>
    <p>
      <strong>结构位止损</strong>：把止损价放在关键价格结构的外侧一点，结构被跌穿，逻辑即失效。
      常见结构：前期明显低点、盘整区下沿、突破后的回踩起点。结构位怎么客观地画（是区域不是一个点、至少两次触及等标准），详见〔B4-C05〕。
    </p>
    <p><em>示例：</em>甲股份入场 10.00 元，前期低点 9.50 元，买入逻辑"站稳低点之上"，止损价 9.50 元——上一章小明用的正是它。</p>
    <ul>
      <li>适用：买入理由本身建立在结构上。止损价与逻辑天然对齐，结构破了，理由就没了。</li>
      <li>缺点一，主观：同一张图，两人可能画出不同位置（客观标准见〔B4-C05〕）。</li>
      <li>缺点二，只管位置不管宽度：贴得近的结构位，在波动大的股票上照样被日常波动打穿。</li>
      <li>缺点三，价格偶尔触及就反转，止损卖在阶段低点附近；可用波动余量缓解——这就要用 ATR。</li>
    </ul>
    <p><strong>方法二：ATR 止损——管"留多宽"。</strong></p>
    <p>
      <strong>ATR</strong>（平均真实波幅）：最近一段时期标的平均每天波动的幅度，最常用 14 日，即"过去 14 个交易日平均一天走多少"。
      它衡量波动大小，不指示方向。真实波幅与普通波幅的区别、逐日计算，详见〔B4-C07〕。
    </p>
    <div class="formula-block">
      用法一：止损价 = 入场价 − 2 × ATR(14)（示例参数，未经验证）<br />
      用法二：止损价 = 结构位 − 0.5 × ATR（示例参数）——位置听结构的，宽度听波动的
    </div>
    <ul>
      <li>适用：趋势跟踪等不依赖固定结构的做法；给任何止损位统一加波动余量。</li>
      <li>缺点一，不指出失效点在哪：纯 ATR 止损与逻辑脱钩，跌破 2×ATR 不必然等于逻辑失效。</li>
      <li>缺点二，ATR 会变：连续大涨大跌后 ATR 抬高，止损距离跟着漂；参数定死后不随意改。</li>
      <li>缺点三，ATR 是平均值，极端单日可远超它，更防不住跳空（〔B3-C06〕）。</li>
    </ul>
    <p><strong>方法三：固定百分比止损——极简与兜底。</strong></p>
    <p><strong>固定百分比止损</strong>：止损距离 = 入场价 × 固定比例，如 5%（起步参考值，需个人校准）。</p>
    <p><em>示例：</em>入场 20.00 元，固定 5%，止损 = 19.00 元，距离 1 元。</p>
    <ul>
      <li>适用：完全不看图的极简做法；宽基 ETF 与定投式分批；或作"绝对底线"叠在其他方法之下，如止损距离不超过 8%（示例参数）。</li>
      <li>缺点：与波动、结构都脱钩。同样 5%，对日均波动 5% 的股票只是一个正常波动日，对日均波动 0.5% 的股票又宽得离谱。</li>
    </ul>

    <h3 id="c05-s3" class="sub-title" data-spy>三、统一算例 EX-D：同样的价格，不同的波动</h3>
    <p>
      本金 100,000 元（EX-A），单笔风险比例 1%，1R = 1,000 元。
      两只虚构标的价格相同，波动相差 10 倍：X 股价 20 元、ATR 1.0 元（日均约 5%）；Y 股价 20 元、ATR 0.1 元（日均约 0.5%）。
      两家都按"入场价 − 2×ATR"定止损（示例参数）。本章算例缓冲取 0，聚焦止损本身。
    </p>
    <p><strong>X 的计算：</strong>止损价 = 20 − 2 = 18.00 元，距离 2 元（10%）；每股风险 2 元；
    股数 = 1,000 ÷ 2 = 500 股；金额 10,000 元（10%），未超单票上限；实际计划亏损 = 1,000 元 = 1R。一切正常。</p>
    <p><strong>Y 的计算：</strong></p>
    <ol>
      <li>止损价 = 20 − 0.2 = 19.80 元，距离 0.2 元，占价格仅 1%。</li>
      <li>每股风险 = 0.20 元。</li>
      <li>公式股数 = 1,000 ÷ 0.20 = 5,000 股，金额 = 100,000 元，占本金 100%。</li>
      <li>校验单票上限（20%）：20,000 ÷ 20 = <strong>1,000 股</strong>。公式股数被单票上限压住了。</li>
      <li>实际计划亏损 = 1,000 × 0.20 = 200 元，只有 0.2R。</li>
    </ol>
    <p><strong>EX-D 的三个发现：</strong></p>
    <ol>
      <li>
        <strong>价格相同，风险结构完全不同。</strong>同一条"2×ATR"，X 的距离是 10%，Y 只有 1%。
        决定止损距离的不是价格，是波动；决定股数的不是感觉，是止损距离。
      </li>
      <li>
        <strong>止损太近，公式会"想要"满仓。</strong>Y 的公式股数等于全部本金，单票上限是最后一道闸，
        把它压回 1,000 股——没有这道闸，一个过近的止损就能推着账户满仓。
      </li>
      <li>
        <strong>被压住之后，预算用不满。</strong>Y 的实际风险只有 0.2R。这不是占便宜：0.2 元只相当于两个平均波动日，
        连续两天普通下跌就会触发。"止损太紧"同时表现为"仓位顶格"与"极易被洗出"，预算大量闲置正是止损过近的信号。
      </li>
    </ol>
    <p>
      再把固定 5% 放进同一坐标系。5% 的距离是 1 元：对 X，1 ÷ 1.0 = 1×ATR，一个正常波动日就可能触发；
      对 Y，1 ÷ 0.1 = 10×ATR，要连跌十个平均日。"每只股票统一 5%"错在哪，数字已经给出答案。
    </p>

    <h3 id="c05-s4" class="sub-title" data-spy>四、两种极端：太紧与太宽</h3>
    <p>
      继续用 X（股价 20 元，ATR 1.0，失效点 18.00 元，1R = 1,000 元），把止损往两边推。本节数字为独立示意，基于 EX-D 延伸。
    </p>
    <p><strong>太紧：0.5×ATR，被噪音洗出。</strong>小王觉得"一次亏 1,000 元太多"，把止损收到 19.50 元：</p>
    <ol>
      <li>每股风险 0.5 元，公式股数 = 2,000 股，超单票上限被压到 1,000 股；单次亏损 = 500 元，看似"更安全"。</li>
      <li>
        但 X 平均一天走 1 元，0.5 元不足半个平均波幅。买入后回调 0.5 元——几乎每天都有的事——就触发止损，亏 500 元出局；
        三天后价格回到 20 元上方继续走向原目标，失效点 18.00 元从未被碰到。
      </li>
      <li>假设一个月被洗出 3 次：3 × 500 = 1,500 元，即 1.5R，比一次"恰当止损"还贵一半。</li>
    </ol>
    <p>
      与买入逻辑无关的日常波动称为<strong>噪音</strong>：不是消息也不是趋势，只是价格的日常起伏，尺度可用 ATR 估计。
      止损放进噪音的活动范围就会被反复收割——紧止损省下的不是钱，它把一次大的换成多次小的，总和更高，外加踏空。
    </p>
    <p><strong>太宽：4×ATR，仓位缩水。</strong>小刘相反，"给足空间"，止损放到 16.00 元，距离 4 元：</p>
    <ol>
      <li>每股风险 4 元，公式股数 250 股，取整 200 股；金额 4,000 元，占 4%，仓位从 10% 缩到 4%。</li>
      <li>
        盈亏比变差。设目标价 24 元（独立示意）：止损 18 元时，盈亏比 =（24 − 20）÷ 2 = 2；
        止损 16 元时 = 4 ÷ 4 = 1。同样看对一次，500 股赚 2,000 元（2R），200 股只赚 800 元（0.8R）。
      </li>
      <li>价格跌到 18 元时逻辑已不成立，小刘还抱着失效的逻辑滑向 16 元；多出的距离没有换来任何与逻辑有关的好处。</li>
    </ol>
    <p>
      <strong>恰当的做法是两者配合：位置听结构的，宽度听波动的。</strong>
      担心价格插到结构位就反转，可把止损往外挪半个 ATR，如 18 − 0.5 = 17.50 元（示例参数）；
      放到 16 元则远超波动依据，只是把仓位白白让出去。
    </p>
