      让"谁和谁一组、哪组超限"一眼可见。每开一笔之前先填表，填完再下单，这是〔B3-C03〕"先算风险，再找买点"在组合层的落实。
    </p>
    <p>登记表分两部分。第一部分是持仓明细（EX-O 组合加两笔其他持仓做示范，除 EX-O 数字外为独立示意）：</p>
