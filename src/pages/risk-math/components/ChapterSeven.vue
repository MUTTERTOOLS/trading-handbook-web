    <h3 id="c07-c" class="sub-title" data-spy>速查卡</h3>
    <div class="cheat-card">
      <p><strong>四个抓手（命中任一即同组）</strong>：同行业 ／ 同主题 ／ 同风格 ／ 同指数成分。</p>
      <div class="cc-title" style="margin-top: 10px;">两个公式</div>
      <ul style="padding-left: 20px;">
        <li>计划口径：在途总风险 = 各笔计划亏损之和 ÷ 本金。</li>
        <li>合并口径：在途总风险 = 各组组风险之和；组风险 = 组合计仓位 × 组坏情形幅度。</li>
      </ul>
      <p style="margin-top: 8px;"><strong>判断顺序</strong>：分组 → 定坏情形幅度 → 算组风险 → 两个口径对照上限 → 组满即停。</p>
      <p><strong>EX-O 参考</strong>：5 只同板块各 15%（合计 75%），行业利空跳空 −8% → 每只亏 1.2% 本金，合计 6.0% &gt; 5% 上限。</p>
      <p><strong>起步参考值</strong>：在途总风险上限 5%（常见取值 4%~6%）；单票上限 20%（宽基 ETF 除外）。均为起步参考值，需个人校准。</p>
