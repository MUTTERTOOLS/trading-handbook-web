      <li>造出新理由："跌这么多了，不如长期拿着吧。"</li>
    </ol>
    <p>
      识别方法只需一张纸：把买入当天的书面理由抄下来，再写下今天继续持有的理由，两句话如果不是同一句，就是换了理由。
      按本丛书的口径，<strong>亏损后改变理由并据此继续持有，属于执行违规</strong>（机制见〔B3-C03〕典型二；违规分级见〔B7-C09〕）。
      <strong>理由可以换，仓位不能原地续命。</strong>
    </p>
    <p class="table-note">还要提醒一句：把七种退出写齐，只是规则完整；规则完整不等于规则有效，有效性要靠〔B6-C12〕的验证流程。</p>

    <h3 id="c09-m" class="sub-title" data-spy>常见误区</h3>
    <Callout variant="warn" title="误区一：“到了目标价，再拿一会儿，让利润奔跑。”">
      <p>
        <strong>为什么错：</strong>目标止盈的依据是买入时的赔率计算。"再拿一会儿"没有新理由，只是浮盈带来的舍不得。
        到目标后继续持有的边际赔率往往已经明显恶化（本章算过：2.0 → 0.15）。
        若真想"让利润奔跑"，应在买入前写明跟踪止盈的规则，而不是事后口头改。
      </p>
      <p><strong>正确做法：</strong>目标止盈与跟踪止盈二选一，买入前固定；要换写法，盘后按改规则流程处理（〔B7-C09〕）。</p>
    </Callout>
    <Callout variant="warn" title="误区二：“亏了不卖就不算亏，我改做长线。”">
      <p>
        <strong>为什么错：</strong>浮亏已按账户权益计入，是既成事实；改理由改变的是说法，不是亏损。
        新理由没有止损、没有期限、没有 1R，等于把计划外亏损扛成无上限风险。
        这是"套牢改长线"的标准形态，属执行违规。
      </p>
      <p><strong>正确做法：</strong>先按原触发语句执行退出；若想按新逻辑持有，盘后作为新决策重新走五步（〔B3-C03〕）。</p>
    </Callout>
    <Callout variant="warn" title="误区三：“出现更看好的标的，随时可以换过去。”">
      <p>
        <strong>为什么错：</strong>没有量化门槛与频率上限的换仓，会退化成追涨——每次都卖在犹豫、买在兴奋，
        还要重复支付费用与滑点。换仓的理由是"边际赔率的比较结果"，不是"新鲜感"。
      </p>
      <p><strong>正确做法：</strong>换仓门槛（赔率差）与频率上限在买入前写进触发语句；每次换仓按〔B3-C04〕重算仓位。</p>
    </Callout>

