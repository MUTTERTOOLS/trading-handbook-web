    <h3 id="c02-s3" class="sub-title" data-spy>三、小优势加大仓位：EX-J 的算术</h3>
    <p>
      上面四个账户，没有一个需要"什么都不懂"才会走进去，其中几个甚至自认为有优势。那就把"优势"直接放进算术里看。
    </p>
    <p>
      思想实验的设定（EX-J）：胜率 55%——高于纯随机的五成，算是有优势；每次全仓；一次判断错误即归零
      （比如全仓遇上连续跌停，或杠杆爆仓）。
    </p>
    <div class="callout callout-key">
      <div class="callout-title">EX-J（总编修订后的统一措辞）</div>
      <p><strong>若每次全仓、一次判断错误即归零，则 10 次都判断正确的概率仅 0.55¹⁰≈0.25%，存活到第 11 次几乎不可能。</strong></p>
    </div>
    <p>把 0.55¹⁰ 算一遍：</p>
    <ul>
      <li>0.55² = 0.3025</li>
      <li>0.55⁴ = 0.3025 × 0.3025 ≈ 0.0915</li>
      <li>0.55⁵ = 0.0915 × 0.55 ≈ 0.0503</li>
      <li>0.55¹⁰ = 0.0503 × 0.0503 ≈ 0.0025，即约 0.25%</li>
    </ul>
    <p>验算另一条路：0.55⁸ = 0.0915 × 0.0915 ≈ 0.0084；0.0084 × 0.3025 ≈ 0.0025。两条路一致。</p>
    <p>
      0.25% 意味着：每 1,000 个这样交易的人，大约只有 2~3 个能连续全对 10 次。其余 997 人以上，都活不到展示"长期优势"的那一天。
    </p>
    <p><strong>打个比方。</strong>一个抛硬币略占便宜的人，优势要抛上千次才显出来。全仓相当于只许他抛十次，中途一次反面就取消资格——优势再真，也来不及兑现。</p>
    <p class="table-note"><em>类比的局限：</em>硬币的概率固定不变，市场的胜率会漂移；这个比方只演示"仓位砍掉了机会次数"这一件事。</p>
    <p>
      这种"优势挡不住出局"的现象，赌场数学里早有名字。<strong>赌徒破产</strong>说的是：即使每局胜率略高于五成，
      只要每次下注占资金的比例过大、亏光即出局，长期破产概率仍接近必然。本章只给直觉版；严格推导超出本书数学范围（全书只用四则运算与百分比）。
    </p>
    <p>把全仓放宽一点，看中间情形。假设有人每次拿账户的 5% 去冒险、一次错误亏掉这 5%（算术演示，不是建议）：</p>
    <ul>
      <li>胜率 50% 时，100 笔交易的期望最长连亏约 6 笔（EX-R，近似值）。连亏不是坏运气，是常态（分布见〔B6-C02〕）。</li>
      <li>连亏 6 笔：0.95⁶ ≈ 0.735，回撤约 26.5%；连亏 7 笔约 30.2%（EX-I）。</li>
      <li>按回本表（EX-H），回撤 30% 要涨约 43% 才回本。</li>
      <li>同样连亏 7 笔，落在每次 1% 的人身上，回撤约 6.8%（EX-I），是擦伤。</li>
    </ul>
    <p>
      仓位大小不决定连亏会不会来，只决定连亏落地时是擦伤还是骨折（〔B3-C01〕）。
      <strong>优势决定账户的平均速度，仓位决定账户能不能活到平均兑现的那一天。</strong>
    </p>

    <h3 id="c02-s4" class="sub-title" data-spy>四、共同的骨架：单次或累积亏损无上限 + 无预设退出</h3>
    <p>把四个账户并排放，"破产结构"这个词就现出了原形：</p>
    <table class="data-table">
      <thead><tr><th>结构</th><th>亏损怎么变得无上限</th><th>退出在哪里缺席</th></tr></thead>
      <tbody>
        <tr v-for="row in skeletonTable" :key="row.type">
          <td>{{ row.type }}</td>
          <td>{{ row.how }}</td>
          <td>{{ row.miss }}</td>
        </tr>
      </tbody>
    </table>
    <p>
      四个结构，同一副骨架：<strong>单次或累积亏损无上限 + 无预设退出。</strong>
      两条缺一不可：有上限、没退出，亏损会被规则接住；有退出、没上限，最多亏掉预算内的那一笔。
      两个口子同时开着，账户就随时与下一次深亏相连。
    </p>
    <p><strong>打个比方。</strong>破产很少是跳崖，更像下楼梯：每一步都有说得通的理由，回头一看，已在深水区。</p>
    <p class="table-note"><em>类比的局限：</em>楼梯可以原路爬回；深亏后的回本坡度按 EX-H 加速，比下去时陡得多。</p>
    <p>
      还要补两句实话。其一，现实中的破产常是混合结构：重仓加扛单、杠杆加补仓，破坏力相乘。
      其二，这四种是常见的典型，不是完整清单；列出来是给一个检查框架，不是定律。
    </p>
    <p>
      本章留下的是一个诊断工具，两问：<strong>这笔亏损有没有上限？退出条件写下来了吗？</strong>
      堵住这两个口子的方法——先算风险再买（〔B3-C03〕）、把单笔亏损锁成小额（〔B3-C04〕）、买入前写好退出（〔B3-C09〕）、
      账户级停手线（〔B3-C10〕）——都在后面章节。
    </p>

    <h3 id="c02-m" class="sub-title" data-spy>常见误区</h3>
    <Callout variant="warn" title="误区一：“我判断比较准，重仓没事，我会及时止损。”">
      <p>
        <strong>为什么错：</strong>这句话里没有一个可执行的规则。"会及时止损"是意愿：没有价位、没有触发条件、没有写下的动作，
        盘中情绪随时可以改写它。没有写下的规则不算规则。另外两点：其一，即便真想执行，跳空与跌停可能让"及时"落空（〔B3-C06〕）；
        其二，EX-J 说明全仓之下可能没有"下一次"，一次错误就足够出局。
      </p>
      <p><strong>正确做法：</strong>退出条件在买入前写成可检验的语句（怎么写见〔B3-C09〕）；仓位按"错一次也伤不了根本"来定（算法见〔B3-C04〕）。</p>
    </Callout>
    <Callout variant="warn" title="误区二：“我从来不用杠杆，破产跟我没关系。”">
      <p>
        <strong>为什么错：</strong>四种结构里，扛单与马丁式加仓完全不需要杠杆，重仓单票也不需要。
        杠杆只是"无上限"的放大器之一，真正决定破产的是骨架：单次或累积亏损无上限 + 无预设退出。
        小孙和小郑一分钱没借，账户照样走向深水区。
      </p>
      <p><strong>正确做法：</strong>别只检查"借没借钱"，用本章两问检查每一种做法：亏损有没有上限？退出写下来了吗？</p>
    </Callout>
    <Callout variant="warn" title="误区三：“跌了补仓摊低成本，是稳健的做法。”">
      <p>
        <strong>为什么错：</strong>补仓是否稳健，取决于理由与规则。马丁式加仓的问题有三重：加仓的理由是"价格更便宜"，
        而不是"买入逻辑重新成立"；所需资金按倍数增长而资金有限（小郑在第 4 步断裂）；越补越重，退出越来越难。
        摊低本身也慢：价格跌 19%，平均成本只降约 13.7%（小郑的数据）。
      </p>
      <p>
        <strong>正确做法：</strong>加仓要与新建仓过同样的检查：逻辑、证伪点、风险预算一样不缺，并事先写明停止加仓的条件
        （决策顺序见〔B3-C03〕；网格跌穿区间后的预设处理属另一话题，〔B8-C04〕后文详述）。
      </p>
    </Callout>

